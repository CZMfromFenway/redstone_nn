# ---------------------------------------------------------------- 输入编码
def to_float(Xr):
    mu = Xr.mean(0); sd = Xr.std(0); sd[sd < 1e-9] = 1.0
    return (Xr - mu) / sd

def to_int(Xr, levels):
    lo = Xr.min(0); hi = Xr.max(0); rng = np.where(hi - lo > 1e-12, hi - lo, 1.0)
    return np.clip(np.round((Xr - lo) / rng * (levels - 1)), 0, levels - 1).astype(np.int64)

def to_split16(Xr):
    """
    8bit 拆分 -> **8 个数值输入**（不是 one-hot）:
      [hi_1..hi_4, lo_1..lo_4],  每个都是 0~15
    对应强模 LUT 的物理结构: 每条弱模线一个输入。
    第一层是 8->h 的线性层, hi_k 与 lo_k 各有独立权重
    （"高位权搭配低位权"）。
    """
    v = to_int(Xr, 256)
    hi = ((v >> 4) & 0xF).astype(np.float64)
    lo = (v & 0xF).astype(np.float64)
    return np.hstack([hi, lo])                     # (n, 8)

# ---------------------------------------------------------------- 训练
def train_relu(X, Y, h, seed=0, steps=6000, lr=0.03, bs=64):
    """X:(n,d) Y:(n,3) 0/1 ; ReLU 隐藏层 ; 返回 (W1,b1,W2,b2)"""
    rng = np.random.default_rng(seed)
    n, d = X.shape
    W1 = rng.normal(0, 0.5, (h, d)); b1 = np.zeros(h)
    W2 = rng.normal(0, 0.5, (h, 3)); b2 = np.zeros(3)
    ps = [W1, b1, W2, b2]; ms = [np.zeros_like(p) for p in ps]; vs = [np.zeros_like(p) for p in ps]
    best = None
    for t in range(1, steps + 1):
        idx = rng.integers(0, n, bs)
        xb = X[idx]; yb = Y[idx]
        U = xb @ W1.T + b1; Hf = np.maximum(U, 0); Z = Hf @ W2 + b2
        P = 1 / (1 + np.exp(-np.clip(Z, -30, 30)))
        dZ = (P - yb) / bs
        dH = dZ @ W2.T
        dU = dH * (U > 0)
        g = [dU.T @ xb, dU.sum(0), Hf.T @ dZ, dZ.sum(0)]
        for i, (pp, gg) in enumerate(zip(ps, g)):
            ms[i] = 0.9 * ms[i] + 0.1 * gg; vs[i] = 0.999 * vs[i] + 0.001 * gg ** 2
            pp -= lr * (ms[i] / (1 - 0.9 ** t)) / (np.sqrt(vs[i] / (1 - 0.999 ** t)) + 1e-8)
        if t % 1000 == 0 or t == steps:
            Uf = X @ W1.T + b1; Zf = np.maximum(Uf, 0) @ W2 + b2
            acc = ((Zf >= 0).astype(int) == (Y >= 0.5).astype(int)).mean()
            if best is None or acc > best[0]:
                best = (acc, W1.copy(), b1.copy(), W2.copy(), b2.copy())
    return best

def evaluate(params, X, Y, y3):
    _, W1, b1, W2, b2 = params
    Z = np.maximum(X @ W1.T + b1, 0) @ W2 + b2
    bin_acc = ((Z >= 0).astype(int) == (Y >= 0.5).astype(int)).mean()
    pred3 = np.argmax(Z, axis=1)
    acc3 = (pred3 == y3).mean()
    per = [(((Z[:, k] >= 0).astype(int) == (Y[:, k] >= 0.5).astype(int)).mean()) for k in range(3)]
    return bin_acc, acc3, per

