"""v2.3 fixed-benchmark trainer.

Requires four original truth-table .npy files. It never regenerates teachers from seeds.
This is deliberate: the archived reports do not preserve enough RNG details for byte-identical teacher regeneration.

Protocol:
- exact 0..3 pools DD/DT/TD/TT generated by v23_build_exact_pools.py
- mixed-T equal-time: DD/TD/TT 4 passes, DT 2 passes
- full-T equal-scan: DD 4, DT 2, TD/TT 3 passes
- 15 channels, each reads all 4 raw inputs
- channel analog y = sum of 4 unary 0..3 functions, range 0..12
- per-channel head = exact best single-D+threshold binary predicate on 0..12 (158 distinct)
- after each channel, examples misclassified by that channel's own predicate get weight x2, then renormalize
- final 15 bits count 0..15, exact best single-D+threshold predicate on 0..15 (242 distinct)
- coordinate descent: each edge update scans every function in that pool; joint edge tuple is NOT exhaustively enumerated
- repeat multiple initialization seeds and report median / Q1 / Q3 / best.
"""
import os, sys, time, argparse, numpy as np, pandas as pd
from pathlib import Path
PACKAGE_ROOT=Path(__file__).resolve().parent.parent
from DTF004_exact_depth2 import build_base

X=np.indices((16,16,16,16),dtype=np.uint8).reshape(4,-1).T
D,_=build_base(False)

def predicate_library(n):
    s=set()
    for f in D:
        vals=f[:n]
        for k in range(16):
            s.add(tuple(int(v>k) for v in vals))
            s.add(tuple(int(v<=k) for v in vals))
    return np.asarray(sorted(s),dtype=np.uint8)
P13=predicate_library(13); P16=predicate_library(16)
assert len(P13)==158 and len(P16)==242

def best_pred(values,y,w,preds):
    # values in 0..len(predicate)-1. Evaluate all exact single-D predicates.
    pred=preds[:,values]  # P,N; memory manageable: 158*65536 uint8 ~10MB
    err=((pred!=y[None,:])*w[None,:]).sum(axis=1)
    j=int(np.argmin(err))
    return j,float(err[j]),preds[j,values]

def best_edge(pool, xcol, other_sum, y, w, chunk=512):
    # Exact scan over pool. Exploit the 0..3 edge range: for each raw input x and candidate edge value v,
    # precompute the error contribution of all other-sum states for every P13 predicate.
    H=np.zeros((16,10,2),dtype=np.float64)
    np.add.at(H,(xcol,other_sum,y),w)
    E=np.zeros((16,4,len(P13)),dtype=np.float64)
    for xv in range(16):
        for fv in range(4):
            for osum in range(10):
                h0,h1=H[xv,osum]
                if h0==0 and h1==0: continue
                bits=P13[:,fv+osum]
                E[xv,fv] += np.where(bits==0,h1,h0)
    best_e=1e99; best_idx=-1; best_p=-1
    xi=np.arange(16)[:,None]
    for st in range(0,len(pool),chunk):
        F=pool[st:st+chunk].astype(np.intp) # B,16
        # E[x, F[b,x], p] -> x,b,p then sum x
        errs=E[np.arange(16)[None,:],F,:].sum(axis=1) # B,P
        flat=int(np.argmin(errs)); bi,pj=np.unravel_index(flat,errs.shape); e=float(errs[bi,pj])
        if e<best_e: best_e=e; best_idx=st+bi; best_p=pj
    return best_e,best_idx,best_p

def train_channel(pool,y,w,rng,passes):
    edge_idx=rng.integers(0,len(pool),size=4)
    edges=pool[edge_idx].copy()
    head=0
    for _ in range(passes):
        for k in range(4):
            other=np.zeros(len(X),dtype=np.uint8)
            for j in range(4):
                if j!=k: other += edges[j,X[:,j]]
            e,idx,pj=best_edge(pool,X[:,k],other,y,w)
            edge_idx[k]=idx; edges[k]=pool[idx]; head=pj
    vals=sum(edges[j,X[:,j]] for j in range(4)).astype(np.uint8)
    pj,e,pred=best_pred(vals,y,w,P13)
    return vals,pred,edge_idx,pj,e

def train_one(pool,y,seed,passes,m=15,factor=2.0):
    rng=np.random.default_rng(seed); w=np.ones(len(y),dtype=np.float64)/len(y)
    bits=[]; analog=[]; channel_rows=[]; model_edges=[]; model_heads=[]
    t0=time.time()
    for ch in range(m):
        vals,pred,eidx,pj,we=train_channel(pool,y,w,rng,passes)
        analog.append(vals); bits.append(pred); model_edges.append(eidx); model_heads.append(pj)
        wrong=(pred!=y); w*=np.where(wrong,factor,1.0); w/=w.sum()
        cnt=np.sum(np.asarray(bits),axis=0).astype(np.uint8)
        fpj,fe,fp=best_pred(cnt,y,np.ones(len(y))/len(y),P16)
        channel_rows.append((ch+1,int((fp!=y).sum()),100*np.mean(fp!=y),we))
    cnt=np.sum(np.asarray(bits),axis=0).astype(np.uint8)
    fpj,fe,fp=best_pred(cnt,y,np.ones(len(y))/len(y),P16)
    return dict(errors=int((fp!=y).sum()),error_pct=100*np.mean(fp!=y),wall_s=time.time()-t0,final_head=fpj,edge_indices=np.asarray(model_edges),channel_heads=np.asarray(model_heads)),channel_rows

def load_original_teacher(directory, name):
    import hashlib, json
    expected=json.loads((PACKAGE_ROOT/'teacher_validation.json').read_text())
    record=next(r for r in expected if r['name']==name)
    values=np.load(directory/(name+'.npy'),allow_pickle=False)
    if values.shape!=(65536,) or values.dtype.kind not in 'biu' or not np.isin(values,[0,1]).all():
        raise ValueError('Teacher must be the original (65536,) binary integer vector')
    labels=values.astype(np.uint8)
    if hashlib.sha256(labels.tobytes()).hexdigest()!=record['label_sha256']:
        raise ValueError('Teacher label hash differs from recovered original: '+name)
    return labels


def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--teachers',required=True,help='directory containing N4_MLP_T1.npy etc')
    ap.add_argument('--out',default=str(PACKAGE_ROOT/'results')); ap.add_argument('--restarts',type=int,default=7)
    ap.add_argument('--seed0',type=int,default=66000); ap.add_argument('--modes',default='mixedT,fullT')
    args=ap.parse_args(); os.makedirs(args.out,exist_ok=True)
    teachers=['N4_MLP_T1','N4_MLP_T2','N4_COUNT_T1','N4_COUNT_T2']
    for t in teachers:
        p=os.path.join(args.teachers,t+'.npy')
        if not os.path.exists(p): raise FileNotFoundError(f'Missing original fixed truth table: {p}')
    protocol={'mixedT':{'DD':4,'DT':2,'TD':4,'TT':4},'fullT':{'DD':4,'DT':2,'TD':3,'TT':3}}
    rows=[]
    for mode in args.modes.split(','):
      for fam,passes in protocol[mode].items():
        pool=np.load(PACKAGE_ROOT/'exact_pools'/f'{mode}_{fam}_03.npy')
        for teacher in teachers:
          y=load_original_teacher(Path(args.teachers),teacher)
          for r in range(args.restarts):
            seed=args.seed0+1009*r+({'mixedT':0,'fullT':100000}[mode])+({'DD':11,'DT':23,'TD':37,'TT':53}[fam])+({'N4_MLP_T1':101,'N4_MLP_T2':211,'N4_COUNT_T1':307,'N4_COUNT_T2':401}[teacher])
            res,_=train_one(pool,y,seed,passes)
            edges=res.pop('edge_indices'); heads=res.pop('channel_heads')
            model_path=os.path.join(args.out,f'{teacher}_{mode}_{fam}_r{r}.npz')
            np.savez_compressed(model_path,edge_indices=edges,channel_heads=heads,final_head=res['final_head'],pool_sha256=__import__('hashlib').sha256(pool.tobytes()).hexdigest(),teacher=teacher,mode=mode,family=fam,seed=seed,passes=passes)
            rows.append(dict(teacher=teacher,T_mode=mode,family=fam,passes=passes,pool_size=len(pool),restart=r,seed=seed,**res))
            pd.DataFrame(rows).to_csv(os.path.join(args.out,'raw_runs.csv'),index=False)
            print(rows[-1],flush=True)
    df=pd.DataFrame(rows)
    summ=df.groupby(['teacher','T_mode','family','passes','pool_size']).agg(runs=('error_pct','size'),median_pct=('error_pct','median'),q1_pct=('error_pct',lambda x:x.quantile(.25)),q3_pct=('error_pct',lambda x:x.quantile(.75)),best_pct=('error_pct','min'),mean_wall_s=('wall_s','mean')).reset_index()
    summ.to_csv(os.path.join(args.out,'summary.csv'),index=False)
if __name__=='__main__':main()
