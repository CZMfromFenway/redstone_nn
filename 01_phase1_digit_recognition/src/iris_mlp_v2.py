# ---------------------------------------------------------------- 编码（用给定界）
def enc_float(Xtr, Xte):
    mu = Xtr.mean(0); sd = Xtr.std(0); sd[sd < 1e-9] = 1.0
    return (Xtr - mu) / sd, (Xte - mu) / sd

def _q(Xtr, Xte, levels):
    lo = Xtr.min(0); hi = Xtr.max(0); rng = np.where(hi - lo > 1e-12, hi - lo, 1.0)
    f = lambda X: np.clip(np.round((X - lo) / rng * (levels - 1)), 0, levels - 1).astype(np.float64)
    return f(Xtr), f(Xte)

def enc_4bit(Xtr, Xte):
    return _q(Xtr, Xte, 16)

def enc_8bit_split(Xtr, Xte):
    a, b = _q(Xtr, Xte, 256)
    a = a.astype(np.int64); b = b.astype(np.int64)
    f = lambda v: np.hstack([((v >> 4) & 0xF).astype(np.float64), (v & 0xF).astype(np.float64)])
    return f(a), f(b)

